package com.arena.snakesladders.model.enums;

/**
 * Power-up items available on the POWERUP board variant.
 */
public enum PowerUpType {
    /** Negates the next snake slide. */
    SHIELD,
    /** Grants an extra combined roll on the player's next turn. */
    DOUBLE,
    /** Freezes the current leader for one turn. */
    FREEZE
}
